    assertCanMutate(user, tableName, 'delete')

    if (tableName === 'asistencias_curso') {
      const keys = await primaryKeyColumns(pool, tableName)
      const ids = parsePrimaryKeyValues(id, keys.length)
      const where = keys.map((key, index) => `${quoteIdentifier(key)}::text = $${index + 1}`).join(' AND ')
      const existing = await pool.query<Row>(`SELECT * FROM ${quoteIdentifier(tableName)} WHERE ${where}`, ids)
      if (!existing.rows[0]) return { deleted: false }
      assertOwnAttendance(user, existing.rows[0])
    }
    return { deleted: await deleteRow(pool, tableName, id, user) }
