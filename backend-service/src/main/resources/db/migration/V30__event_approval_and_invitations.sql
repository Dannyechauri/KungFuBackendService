ALTER TABLE cursos_agendados
  ADD COLUMN creador_rol TEXT,
  ADD COLUMN creador_id BIGINT,
  ADD COLUMN estado_instructor TEXT NOT NULL DEFAULT 'ACEPTADO'
    CHECK (estado_instructor IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO')),
  ADD CONSTRAINT ck_cursos_agendados_creador CHECK (
    (creador_rol IS NULL AND creador_id IS NULL)
    OR (creador_rol IN ('ADMIN', 'INSTRUCTOR') AND creador_id IS NOT NULL)
  );

ALTER TABLE horarios_recurrentes
  ADD COLUMN creador_rol TEXT,
  ADD COLUMN creador_id BIGINT,
  ADD COLUMN estado_instructor TEXT NOT NULL DEFAULT 'ACEPTADO'
    CHECK (estado_instructor IN ('PENDIENTE', 'ACEPTADO', 'RECHAZADO')),
  ADD CONSTRAINT ck_horarios_recurrentes_creador CHECK (
    (creador_rol IS NULL AND creador_id IS NULL)
    OR (creador_rol IN ('ADMIN', 'INSTRUCTOR') AND creador_id IS NOT NULL)
  );

