CREATE TABLE invitaciones_evento (
  id_invitacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_curso_agendado BIGINT NOT NULL REFERENCES cursos_agendados(id_curso_agendado) ON DELETE CASCADE,
  id_alumno BIGINT NOT NULL REFERENCES alumnos(id_alumno) ON DELETE CASCADE,
  rol TEXT NOT NULL CHECK (rol IN ('ALUMNO', 'INSTRUCTOR')),
  estado TEXT NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'RETIRADA')),
  es_titular BOOLEAN NOT NULL DEFAULT FALSE,
  invitado_por_rol TEXT NOT NULL CHECK (invitado_por_rol IN ('ADMIN', 'INSTRUCTOR')),
  invitado_por_id BIGINT NOT NULL,
  fecha_invitacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_respuesta TIMESTAMPTZ,
  CONSTRAINT uk_invitaciones_evento_alumno UNIQUE (id_curso_agendado, id_alumno)
);

CREATE INDEX idx_invitaciones_evento_pendientes
  ON invitaciones_evento (id_alumno, fecha_invitacion DESC)
  WHERE estado = 'PENDIENTE';