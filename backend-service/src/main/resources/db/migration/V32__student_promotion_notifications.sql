CREATE TABLE avisos_ascenso (
  id_aviso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alumno BIGINT NOT NULL REFERENCES alumnos(id_alumno) ON DELETE CASCADE,
  grado_anterior TEXT NOT NULL,
  grado_nuevo TEXT NOT NULL,
  orden_anterior INTEGER NOT NULL,
  orden_nuevo INTEGER NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_confirmacion TIMESTAMPTZ,
  CONSTRAINT ck_aviso_ascenso_orden CHECK (orden_nuevo > orden_anterior)
);

CREATE INDEX idx_avisos_ascenso_pendientes
  ON avisos_ascenso (id_alumno, fecha_creacion DESC)
  WHERE fecha_confirmacion IS NULL;

CREATE FUNCTION registrar_aviso_ascenso_alumno()
RETURNS TRIGGER AS $$
DECLARE
  old_grade RECORD;
  new_grade RECORD;
BEGIN
  IF NEW.id_grado IS NOT DISTINCT FROM OLD.id_grado THEN
    RETURN NEW;
  END IF;

  SELECT orden_grado, nombre INTO old_grade
  FROM grados WHERE id_grado = OLD.id_grado;
  SELECT orden_grado, nombre INTO new_grade
  FROM grados WHERE id_grado = NEW.id_grado;

  IF new_grade.orden_grado > old_grade.orden_grado THEN
    INSERT INTO avisos_ascenso (id_alumno, grado_anterior, grado_nuevo, orden_anterior, orden_nuevo)
    VALUES (NEW.id_alumno, old_grade.nombre, new_grade.nombre, old_grade.orden_grado, new_grade.orden_grado);
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_avisos_ascenso_alumno
AFTER UPDATE OF id_grado ON alumnos
FOR EACH ROW
EXECUTE FUNCTION registrar_aviso_ascenso_alumno();