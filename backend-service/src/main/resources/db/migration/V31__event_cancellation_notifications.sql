CREATE TABLE avisos_cancelacion_evento (
  id_aviso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_curso_agendado BIGINT NOT NULL REFERENCES cursos_agendados(id_curso_agendado) ON DELETE CASCADE,
  id_alumno BIGINT NOT NULL REFERENCES alumnos(id_alumno) ON DELETE CASCADE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_confirmacion TIMESTAMPTZ,
  CONSTRAINT uk_aviso_cancelacion_evento_alumno UNIQUE (id_curso_agendado, id_alumno)
);

CREATE INDEX idx_avisos_cancelacion_pendientes
  ON avisos_cancelacion_evento (id_alumno, fecha_creacion DESC)
  WHERE fecha_confirmacion IS NULL;