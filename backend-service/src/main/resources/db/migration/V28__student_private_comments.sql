CREATE TABLE alumno_comentarios (
  id_comentario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alumno BIGINT NOT NULL REFERENCES alumnos(id_alumno) ON DELETE CASCADE,
  id_autor BIGINT NOT NULL,
  rol_autor TEXT NOT NULL CHECK (rol_autor IN ('ADMIN', 'INSTRUCTOR')),
  nombre_autor TEXT NOT NULL,
  comentario TEXT NOT NULL CHECK (length(btrim(comentario)) BETWEEN 1 AND 4000),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_alumno_comentarios_alumno_fecha
  ON alumno_comentarios (id_alumno, creado_en DESC, id_comentario DESC);