-- Copia de los datos del evento: si el instructor lo rechaza, el evento se borra y el aviso debe sobrevivir.
CREATE TABLE avisos_respuesta_evento (
  id_aviso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destinatario_rol TEXT NOT NULL CHECK (destinatario_rol IN ('ADMIN', 'INSTRUCTOR')),
  destinatario_id BIGINT NOT NULL,
  decision TEXT NOT NULL CHECK (decision IN ('ACEPTADO', 'RECHAZADO')),
  curso_nombre TEXT NOT NULL,
  instructor_nombre TEXT NOT NULL,
  sala_nombre TEXT,
  fecha_hora TIMESTAMP NOT NULL,
  fecha_hora_fin TIMESTAMP NOT NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_confirmacion TIMESTAMPTZ
);

CREATE INDEX idx_avisos_respuesta_evento_pendientes
  ON avisos_respuesta_evento (destinatario_rol, destinatario_id, fecha_creacion DESC)
  WHERE fecha_confirmacion IS NULL;
